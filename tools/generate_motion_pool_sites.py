"""Generate only R3's interoperability site table from the approved machine-readable ledger.

python tools/generate_motion_pool_sites.py <e4-r2-r3-ledgers.md> [--check]
"""
import argparse
import collections
import hashlib
import re
from pathlib import Path


def generate(ledger):
    blocks = re.findall(r'```ledger\n(.*?)```', ledger, re.S)
    body = next(b for b in blocks if '# row R3' in b)
    rows = [line.split() for line in body.splitlines() if line and not line.startswith('#')]
    assert len(rows) == 82 and all(len(r) == 9 for r in rows)
    assert collections.Counter(r[2] for r in rows) == {
        'alloc': 3, 'bitmap-dwords': 3, 'capacity': 14, 'last-index': 3,
        'pool-field': 54, 'owner-guard': 1, 'reader-guard': 4,
    }
    lines = ['#pragma once', '// Generated by tools/generate_motion_pool_sites.py; do not edit.',
             '// R3 block SHA-256: '+hashlib.sha256(body.encode()).hexdigest(),
             '#include <array>', '#include <cstdint>', '#include <string_view>',
             'namespace motion_pool_sites {',
             'enum class kind { operand, owner_guard, reader_guard };',
             'struct site { std::uint32_t va; std::string_view hex; unsigned offset, size; std::uint32_t old_value, new_value; kind type; };',
             'inline constexpr std::array<site,82> sites{{']
    number = lambda v: '0' if v == '-' else str(int(v))
    value = lambda v: '0' if v == '-' else '0x'+v
    for row in rows:
        va, kind, role, field, off, size, old, new, code = row
        if kind != 'cave':
            raw = bytes.fromhex(code)
            assert int.from_bytes(raw[int(off):int(off)+int(size)], 'little') == int(old, 16)
        tag = role.replace('-', '_') if kind == 'cave' else 'operand'
        lines += ['    // ledger '+' '.join(row),
                  f'    {{0x{va},"{code}",{number(off)},{number(size)},{value(old)},{value(new)},kind::{tag}}},']
    return '\n'.join(lines+['}};', '}'])+'\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('ledger', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(args.ledger.read_text(encoding='utf-8'))
    target = Path(__file__).resolve().parents[1] / 'src/motion_pool_sites.hpp'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != result:
            raise SystemExit('FAIL generated MotionPool table differs from approved R3 ledger')
        print('PASS generated MotionPool table: 82 rows, no difference')
    else:
        target.write_text(result, encoding='utf-8', newline='\n')
        print('Generated', target.name, '(82 R3 rows)')
