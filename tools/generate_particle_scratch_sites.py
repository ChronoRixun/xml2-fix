"""Derive W3-9 count-call spans from the owned retail executable; --check --verify certifies the ledger."""
import argparse
import hashlib
from pathlib import Path
import capstone as C
import pefile

ROOT = Path(__file__).resolve().parents[1]
OPERATIONS = (0x578d20, 0x578e10, 0x578ec0, 0x579000, 0x579290,
              0x5794e0, 0x579600, 0x579800, 0x579910, 0x5799a0, 0x579ae0)
SHA = '146cd9c316edb57a267cd73753a7ce9af647e52aab750d449c6b278fb4a1669b'


def derive(exe, verify=False):
    assert hashlib.sha256(exe.read_bytes()).hexdigest() == SHA, 'unsupported executable'
    pe = pefile.PE(str(exe))
    cs = C.Cs(C.CS_ARCH_X86, C.CS_MODE_32)
    cs.detail = True
    rows = []
    for index, start in enumerate(OPERATIONS):
        end = OPERATIONS[index+1] if index+1 < len(OPERATIONS) else 0x579b50
        insns = list(cs.disasm(pe.get_data(start-0x400000, end-start), start))
        calls = [i for i, x in enumerate(insns) if x.mnemonic == 'call' and x.op_str.endswith('+ 0x74]')]
        assert len(calls) == 1, hex(start)
        i = calls[0]
        call, following = insns[i:i+2]
        assert call.bytes.hex() in ('ff5074', 'ff5274')
        assert following.mnemonic in ('test', 'mov', 'xor', 'fld')
        assert any(x.mnemonic == 'lea' and '+ 0x470]' in x.op_str for x in insns), hex(start)
        rows.append((start, call.address, bytes(call.bytes+following.bytes)))
    if verify:
        # No external direct branch may enter a displaced instruction.
        cs.skipdata = True
        decoded = 0
        for section in pe.sections:
            if not section.Characteristics & 0x20000000:
                continue
            for x in cs.disasm(section.get_data(), 0x400000+section.VirtualAddress):
                if not x.id:
                    continue
                decoded += 1
                if x.group(C.CS_GRP_JUMP) or x.group(C.CS_GRP_CALL):
                    for op in x.operands:
                        if op.type == C.x86.X86_OP_IMM:
                            assert not any(a < op.imm < a+len(b) for _, a, b in rows), hex(x.address)
        print(f'PASS full-text branch scan: {decoded} instructions; no interior entry')
    return rows


def render(rows):
    lines = ['#pragma once', '// Generated by tools/generate_particle_scratch_sites.py; do not edit.',
             '// Retail SHA-256: '+SHA, '#include <array>', '#include <cstdint>', '#include <string_view>',
             'namespace particle_scratch_sites {',
             'inline constexpr unsigned capacity = 40;',
             'struct site { std::uint32_t operation, va; std::string_view hex; };',
             'inline constexpr std::array<site,11> sites{{']
    lines += [f'    {{0x{s:x},0x{a:x},"{b.hex()}"}},' for s, a, b in rows]
    return '\n'.join(lines+['}};', '}'])+'\n'


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('exe', type=Path)
    p.add_argument('--check', action='store_true')
    p.add_argument('--verify', action='store_true')
    args = p.parse_args()
    result = render(derive(args.exe, args.verify))
    target = ROOT/'src/particle_scratch_sites.hpp'
    if args.check:
        assert target.read_text(encoding='utf-8') == result, 'generated ledger differs'
        print('PASS generated ledger: eleven count-call spans, no difference')
    else:
        target.write_text(result, encoding='utf-8', newline='\n')
        print('Generated', target)
