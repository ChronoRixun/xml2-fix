"""Derive W3-3's operands and invariant guards from the retail PE (never execute it).

--verify scans the entire .text for pool field operands and allocator callers.
The schema names fields; instruction bytes, addresses and encoding widths are decoded.
"""
from pathlib import Path
import argparse
import hashlib
import os
import capstone as cs
from capstone.x86 import X86_OP_IMM, X86_OP_MEM
import pefile

ROOT = Path(__file__).resolve().parents[1]
FIELDS = {0x1a960:'bitmap_a', 0x1a98c:'ring', 0x1aec0:'write',
          0x1aec4:'read', 0x1aec8:'free', 0x1aecc:'bitmap_b', 0x1aef8:'live'}
SPANS = [(0x4f5970,0x4f5a09), (0x4f6260,0x4f6303), (0x4f7570,0x4f75d2),
         (0x4f7a40,0x4f7a86), (0x4f7a90,0x4f7ac3), (0x5001d0,0x500232),
         (0x5003c0,0x500453), (0x500de0,0x500e6b)]
# Whole instructions pin the unchanged stride, caller ABI, map cap and entry cave.
GUARDS = [(0x500de0,6,'allocation entry prologue'),
          (0x500df8,6,'record stride'), (0x5003c8,6,'free record stride'),
          (0x4f62d2,6,'teardown record stride'),
          (0x500b94,17,'pointer to index division by 0x148'),
          (0x5011c6,19,'style ECX, sole caller and ignored AL'),
          (0x500e5a,8,'style plus 0x74 map insertion'),
          (0x500274,6,'map capacity stays 150'),
          (0x500292,6,'node live at style plus 0x74 plus 0xc plus 0xbe0 = 0xc60'),
          (0x4f7a90,9,'lazy singleton getter'),
          (0x500afd,5,'sole move constructor call')]

def generate(exe, verify=False):
    data = Path(exe).read_bytes()
    assert hashlib.sha256(data).hexdigest() == '146cd9c316edb57a267cd73753a7ce9af647e52aab750d449c6b278fb4a1669b', 'wrong retail executable'
    pe = pefile.PE(data=data)
    md = cs.Cs(cs.CS_ARCH_X86,cs.CS_MODE_32)
    md.detail = True
    def decode(lo,hi):
        return md.disasm(pe.get_data(lo-0x400000,hi-lo),lo)
    rows=[]
    for lo,hi in SPANS:
        for ins in decode(lo,hi):
            for op in ins.operands:
                field=None
                if op.type==X86_OP_MEM and op.mem.disp in FIELDS:
                    off,width,value=ins.disp_offset,ins.disp_size,op.mem.disp
                    field=FIELDS[value]
                elif op.type==X86_OP_IMM:
                    value=op.imm
                    field = ('capacity' if value==332 else 'last_index' if value==331
                             else 'size' if value==0x1aefc
                             else 'words' if value==11 and ins.mnemonic=='mov' else None)
                    off,width=ins.imm_offset,ins.imm_size
                if field:
                    assert width==4 and int.from_bytes(ins.bytes[off:off+width],'little')==value
                    rows.append((ins.address,ins.bytes.hex(),off,width,value,field))
    assert len(rows)==56, f'unexpected ledger size {len(rows)}'
    if verify:
        section=next(s for s in pe.sections if s.Name.startswith(b'.text'))
        lite=cs.Cs(cs.CS_ARCH_X86,cs.CS_MODE_32);lite.skipdata=True
        found=set(); calls={0x500de0:[],0x5001d0:[],0x4f5970:[]}
        for va,size,mn,ops in lite.disasm_lite(section.get_data(),0x400000+section.VirtualAddress):
            raw=pe.get_data(va-0x400000,size)
            if mn=='call' and raw[0]==0xe8:
                target=(va+size+int.from_bytes(raw[1:5],'little',signed=True))&0xffffffff
                if target in calls:calls[target].append(va)
            if not any(v.to_bytes(4,'little') in raw for v in FIELDS):continue
            ins=next(decode(va,va+size),None)
            if ins:
                for op in ins.operands:
                    if op.type==X86_OP_MEM and op.mem.disp in FIELDS:found.add((va,ins.disp_offset))
        expected={(r[0],r[2]) for r in rows if r[4] in FIELDS}
        assert found==expected, f'unclassified field operands {found-expected}; missing {expected-found}'
        assert calls=={0x500de0:[0x5011cc],0x5001d0:[0x500def],0x4f5970:[0x4f62e7]}, calls
    header='// Generated by tools/w3_fightmoves_ledger.py; do not edit.\n'
    header+=f'inline constexpr std::array<site, {len(rows)}> sites{{{{\n'
    header+=''.join(f'\t{{0x{va:x}, "{b}", {off}, {width}, field::{f}}},\n' for va,b,off,width,value,f in rows)+'}};\n\n'
    header+=f'inline constexpr std::array<limits_rules::guard, {len(GUARDS)}> guards{{{{\n'
    for va,size,what in GUARDS:
        decoded=list(decode(va,va+size))
        assert sum(i.size for i in decoded)==size, f'guard splits instruction {va:x}'
        header+=f'\t{{0x{va:x}, "{pe.get_data(va-0x400000,size).hex()}", "{what}"}},\n'
    header+='}};\n'
    return header,rows

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--exe',default=os.environ.get('XML2_FIX_TEST_EXE'))
    parser.add_argument('--check',action='store_true');parser.add_argument('--verify',action='store_true')
    args=parser.parse_args()
    if not args.exe:parser.error('set XML2_FIX_TEST_EXE or --exe')
    header,rows=generate(args.exe,args.verify)
    path=ROOT/'src/w3_fightmoves_sites.hpp'
    if args.check:assert path.read_text()==header,'generated header stale'
    else:path.write_text(header,encoding='utf-8',newline='\n')
    print(f'PASS FightMoves ledger: {len(rows)} operands; {len(GUARDS)} invariant guards; unclassified 0')

if __name__=='__main__':main()
