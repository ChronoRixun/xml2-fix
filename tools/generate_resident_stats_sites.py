"""Generate the R2 table from the approved ledger; whole retail bodies stay private."""
import argparse
import hashlib
import re
from pathlib import Path

def generate(text):
 body=next(b for b in re.findall(r'```ledger\n(.*?)```',text,re.S) if '# row R2' in b)
 digest=hashlib.sha256(body.encode()).hexdigest()
 assert digest=='5111dd02726c6b3fc120b42ccf414fe4f33fad6a3b9cb1d96a3635df59bd0fb0'
 rows=[s.split() for s in body.splitlines() if s and not s.startswith('#')];assert len(rows)==275
 lines=['#pragma once','// Generated by tools/generate_resident_stats_sites.py; do not edit.',
        '// R2 block SHA-256: '+digest,'#include <array>','#include <cstdint>','#include <string_view>',
        'namespace resident_stats_sites {','enum class kind { operand, incave, cave, rewrite, replace_ };',
        'struct site { std::uint32_t va; kind type; std::string_view role,field,hex,replacement,hash; unsigned span,offset,size; std::uint32_t old_value,new_value; };',
        'inline constexpr std::array<site,275> sites{{']
 for row in rows:
  va,k,role,field,off,size,old,new,hx=row;raw=bytes.fromhex(hx);n=len(raw)
  tag='operand' if k in ('disp32','imm32','imm8') else 'replace_' if k=='replace' else k
  replacement=new if k=='rewrite' else ''
  value=lambda v:'0' if v=='-' else '0x'+v
  oldv=value(old);newv='0' if k=='rewrite' else value(new)
  o='0' if off=='-' else off;z='0' if size=='-' else size
  if k=='replace':hx=raw[:5].hex()
  lines+=['    // row SHA-256: '+hashlib.sha256(' '.join(row).encode()).hexdigest(),
          f'    {{0x{va},kind::{tag},"{role}","{field}","{hx}","{replacement}","{hashlib.sha256(raw).hexdigest()}",{n},{o},{z},{oldv},{newv}}},']
 return '\n'.join(lines+['}};','}'])+'\n'

if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('ledger',type=Path);p.add_argument('--check',action='store_true');a=p.parse_args()
 out=Path(__file__).resolve().parents[1]/'src/resident_stats_sites.hpp';text=generate(a.ledger.read_text(encoding='utf-8'))
 if a.check:
  assert out.exists() and out.read_text(encoding='utf-8')==text,'generated R2 table differs'
  print('PASS R2 table: 275 rows, canonical hash and generated output identical')
 else:out.write_text(text,encoding='utf-8',newline='\n');print('Generated R2 table: 275 rows, full-function hashes only')
