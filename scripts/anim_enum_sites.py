"""Generate the DESIGN 2.3 instruction ledger from the owned retail executable.

python -B scripts/anim_enum_sites.py <retail-exe> [--check]
Only instruction guard bytes and operand recipes are emitted; no game content.
"""
import hashlib, json, struct, sys
from pathlib import Path
import capstone, pefile

R = Path(__file__).resolve().parents[1]
pe = pefile.PE(sys.argv[1], fast_load=True)
data = Path(sys.argv[1]).read_bytes()
_audited = bytearray(data)                    # a Legends Classic build's exe: the retail one with the LAA flag (E12)
_audited[struct.unpack_from('<I', data, 0x3C)[0] + 0x16] &= ~0x20
assert pe.OPTIONAL_HEADER.ImageBase == 0x400000
assert hashlib.sha256(_audited).hexdigest() == '146cd9c316edb57a267cd73753a7ce9af647e52aab750d449c6b278fb4a1669b', 'not the audited retail executable'
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
md.detail = True
rows = []

def add(row, va, expr=None, field='imm', second=None, kind='operand'):
    off = pe.get_offset_from_rva(va - pe.OPTIONAL_HEADER.ImageBase)
    ins = next(md.disasm(data[off:off+15], va))
    n = ins.size if kind == 'operand' else 5 if kind == 'bound' or row == 'M1' else 7
    edits = []
    if expr:
        pos = ins.disp_offset if field == 'disp' else ins.imm_offset
        size = ins.disp_size if field == 'disp' else ins.imm_size
        assert size == 4
        edits.append([pos, expr])
    if second:
        assert ins.imm_size == 4
        edits.append([ins.imm_offset, second])
    rows.append(dict(row=row,va=va,kind=kind,old=data[off:off+n].hex(),edits=edits))

for row,a,b,c in [('C1',0x42196d,0x421972,0x421978),('C2',0x425f04,0x425f09,0x425f0f)]:
    add(row,a,kind='bound');add(row,b,'stride');add(row,c,'cache')
add('C3',0x425f3b,'cache+4');add('C3',0x425f8e,'stride');add('C3',0x425f94,'cache+4+records*stride')
for a in [0x425fd8,0x426004]:add('C4',a,'stride');add('C4',a+6,'cache')
add('C5',0x42612b,'enums')
for a,off in zip([0x426142,0x426173,0x4261a4,0x4261d5,0x426206,0x426237,0x426268,0x426299],[0x24,0x28,0x2c,0x30,0x68,0x6c,0x70,0x74]):
    add('C6',a,'stride');add('C6',a+6,f'cache+{off}','disp')
for a in [0x426165,0x426196,0x4261c7,0x4261f8,0x426229,0x42625a,0x42628b,0x4262bc,0x4262c2,0x4262c8,0x4262d4,0x4262da,0x4262e0,0x4262ec,0x4262f2,0x4262f8,0x426304]:
    off=pe.get_offset_from_rva(a-0x400000);i=next(md.disasm(data[off:off+15],a))
    old=struct.unpack_from('<I',i.bytes,i.disp_offset)[0]
    add('C7',a,f'floats+{old-0x358}','disp')
add('C8',0x425e5b,'enums');add('C8',0x425e6e,'enums-1')
for a in [0x425e64,0x425e73]:add('C8',a,'count','disp')
add('C8',0x425e79,'floats','disp');add('C8',0x425e7f,'count','disp','enums')
add('C9',0x425c32,'count-8','disp')
add('C10',0x425b7a,'stride/4');add('C10',0x425b82,'cache+floats','disp')
add('C11',0x42ead0,'count','disp')
for row,a in [('C12',0x42f0aa),('C13',0x430cdb)]:
    add(row,a,kind='bound');add(row,a+5,'stride');add(row,a+11,'cache+1','disp')
    delta=36 if row=='C12' else 35
    add(row,a+delta,'cache+count','disp');add(row,a+delta+8,'cache+8','disp')
add('C14',0x4310ff,kind='bound');add('C14',0x431104,'stride');add('C14',0x43110a,'cache+1','disp');add('C14',0x43111d,'cache','disp')
add('T1',0x425b96,'enums');add('T1',0x425bac,'table_count','disp')
for a in [0x42633f,0x4263b4,0x4263ca]:add('T2',a,'table_count','disp')
for a in [0x42675e,0x42676e,0x42678b]:add('T3',a,'table_count','disp')
add('T3',0x426764,'enums')
for a in [0x426060,0x426099]:add('T4',a,'table+table_count','disp')
add('T4',0x426078,'table','disp');add('T4',0x4260a1,'table+4','disp')
add('T5',0x427c3a,'table');add('T5',0x427c47,'table')
add('M1',0x427c30,kind='hook');add('M2',0x4265c0,kind='hook')
assert len(rows)==88 and sum(x['kind']=='operand' for x in rows)==81

exprs=list(dict.fromkeys(e[1] for r in rows for e in r['edits']))
names={e:'v'+str(i) for i,e in enumerate(exprs)}
header='// Generated by scripts/anim_enum_sites.py; DESIGN section 2.3.\n#pragma once\n#include "anim_enum_layout.hpp"\n#include <array>\n#include <cstdint>\n#include <string_view>\nnamespace anim_enum_sites {\n'
header+='enum class value { '+', '.join(names.values())+' };\n'
header+='inline std::uint32_t resolve(value v, std::uint32_t cache, std::uint32_t table) {\nusing namespace anim_enum_layout;\nconstexpr auto enums=raised.enums, records=raised.records, stride=raised.record_stride, count=raised.count_off, floats=raised.floats_off, table_count=raised.table_count_off;\nswitch(v) {\n'
for e,n in names.items():header+=f'case value::{n}: return {e};\n'
header+='} return 0; }\nenum class kind { operand, bound, hook };\nstruct edit { unsigned offset; value expression; };\nstruct site { std::string_view row; std::uint32_t va; kind type; std::string_view old_hex; std::array<edit,2> edits; unsigned edit_count; };\ninline constexpr std::array<site,88> sites{{\n'
for r in rows:
    ed=', '.join('{'+str(o)+',value::'+names[e]+'}' for o,e in r['edits'])
    header+=f'{{"{r["row"]}",0x{r["va"]:x},kind::{r["kind"]},"{r["old"]}",{{{{{ed}}}}},{len(r["edits"])} }},\n'
header+='}};\n}\n'
outputs={R/'src/anim_enum_sites.hpp':header,R/'test/anim_enum_sites.json':json.dumps(rows,indent=2)+'\n'}
for p,s in outputs.items():
    if '--check' in sys.argv:assert p.read_text()==s, f'stale {p}'
    else:p.write_text(s,encoding='utf-8',newline='\n')
print('PASS retail instruction guards and generated ledger: 81 + 5 + 2')
